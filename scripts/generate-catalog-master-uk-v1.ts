type Item = readonly [string, string];

function items(...names: string[]): Item[] {
  const seen = new Set<string>();
  const out: Item[] = [];
  for (const name of names) {
    const slug = slugify(name);
    if (seen.has(slug)) continue;
    seen.add(slug);
    out.push([name, slug] as const);
  }
  return out;
}

function dept(name: string, slug: string, ...productTypes: string[]) {
  return { name, slug, items: items(...productTypes) };
}

